//! Build-time registry generation for Minecraft Java 1.21.1 (protocol 767).
//!
//! Inputs are the vanilla data-pack JSON files extracted from the SHA-1 pinned
//! official server JAR. No network, Java process, or third-party registry snapshot
//! is used here. Acquisition and cache policy belong to build.rs.
//!
//! Vanilla's data-pack biome codec contains server-only world-generation fields;
//! its network codec contains only climate and effects. The other ten registry
//! element JSON representations are also accepted by their network codecs.
//! Minecraft codecs read numeric NBT via Number conversions, not one required
//! primitive width: preserve integers exactly as Int/Long, decimal JSON as Double,
//! booleans as Byte. Lists are homogeneous NBT and never silently truncate values.
//! Version references:
//! https://mappings.dev/1.21.1/net/minecraft/world/level/biome/Biome.html
//! https://mappings.dev/1.21.1/net/minecraft/resources/RegistryDataLoader.html
//! https://piston-data.mojang.com/v1/objects/59353fb40c36d304f2035d51e7d6e6baa98dc05c/server.jar
use serde_json::Value;
use std::{
    fmt::Write as _,
    fs,
    io::{self, Read},
    path::Path,
};

const VERSION: &str = "1.21.1";
const SERVER_SHA1: &str = "59353fb40c36d304f2035d51e7d6e6baa98dc05c";
const MAX_PACKET_BYTES: usize = 2_097_150; // Outer frame also contains one packet-ID byte.
const MAX_JSON_BYTES: usize = 1024 * 1024;
const MAX_TOTAL_JSON_BYTES: usize = 16 * MAX_JSON_BYTES;
const MAX_DEPTH: usize = 64;
const MAX_LIST_ENTRIES: usize = 16_384;
const REGISTRIES: [(&str, usize); 11] = [
    ("worldgen/biome", 64),
    ("chat_type", 7),
    ("trim_pattern", 18),
    ("trim_material", 10),
    ("wolf_variant", 9),
    ("painting_variant", 50),
    ("dimension_type", 4),
    ("damage_type", 47),
    ("banner_pattern", 43),
    ("enchantment", 42),
    ("jukebox_song", 19),
];
const BIOME_NETWORK_FIELDS: [&str; 5] = [
    "has_precipitation",
    "temperature",
    "temperature_modifier",
    "downfall",
    "effects",
];

struct Registry {
    name: String,
    count: usize,
    body: Vec<u8>,
    entries: Vec<String>,
}

/// Generate deterministic standalone Rust constants from an extracted
/// `data/minecraft` directory. Returned packets exclude packet IDs and framing.
pub fn generate(root: &Path) -> io::Result<String> {
    let registries = build_registries(root)?;
    let mut source = String::from(
        "// @generated from the official Minecraft server data pack. Do not edit.\n\
         // Generated bytes retain Minecraft's original data rights.\n",
    );
    writeln!(source, "pub const MINECRAFT_VERSION: &str = {VERSION:?};").unwrap();
    writeln!(source, "pub const SOURCE_JAR_SHA1: &str = {SERVER_SHA1:?};").unwrap();
    source.push_str(
        "pub const PLAINS_BIOME_ID: i32 = 0;\n\
         pub const OVERWORLD_DIMENSION_ID: i32 = 0;\n\
         pub const REGISTRY_NAMES: &[&str] = &[\n",
    );
    for registry in &registries {
        writeln!(source, "    {:?},", registry.name).unwrap();
    }
    source.push_str("];\npub const REGISTRY_COUNTS: &[usize] = &[");
    for registry in &registries {
        write!(source, "{},", registry.count).unwrap();
    }
    source.push_str("];\npub const REGISTRY_PACKETS: &[&[u8]] = &[\n");
    for registry in &registries {
        writeln!(
            source,
            "    // {}: {} entries",
            registry.name, registry.count
        )
        .unwrap();
        source.push_str("    &[\n");
        for chunk in registry.body.chunks(24) {
            source.push_str("        ");
            for byte in chunk {
                write!(source, "0x{byte:02x},").unwrap();
            }
            source.push('\n');
        }
        source.push_str("    ],\n");
    }
    source.push_str("];\n");
    let ids = registries
        .iter()
        .map(|registry| (registry.name.clone(), registry.entries.clone()))
        .collect();
    let tags = crate::tags::generate(root, &ids)?;
    source.push_str("pub const TAG_REGISTRY_NAMES: &[&str] = &[\n");
    for (name, _) in &tags.counts {
        writeln!(source, "    {name:?},").unwrap();
    }
    source.push_str("];\npub const TAG_COUNTS: &[usize] = &[");
    for (_, count) in &tags.counts {
        write!(source, "{count},").unwrap();
    }
    source.push_str("];\npub const TAGS_PACKET: &[u8] = &[\n");
    for chunk in tags.body.chunks(24) {
        source.push_str("    ");
        for byte in chunk {
            write!(source, "0x{byte:02x},").unwrap();
        }
        source.push('\n');
    }
    source.push_str("];\n");
    Ok(source)
}

fn build_registries(root: &Path) -> io::Result<Vec<Registry>> {
    let mut total_bytes = 0usize;
    let mut output = Vec::with_capacity(REGISTRIES.len());
    for (registry, expected_count) in REGISTRIES {
        let directory = root.join(registry);
        let mut entries = Vec::new();
        for item in fs::read_dir(&directory).map_err(|e| context(&directory, e))? {
            let item = item.map_err(|e| context(&directory, e))?;
            let path = item.path();
            if path.extension().is_none_or(|extension| extension != "json") {
                continue;
            }
            if !item.file_type()?.is_file() {
                return Err(context(
                    &path,
                    invalid("registry input must be a regular file"),
                ));
            }
            let name = path
                .file_stem()
                .and_then(|name| name.to_str())
                .ok_or_else(|| context(&path, invalid("invalid registry entry filename")))?;
            if !valid_entry_name(name) {
                return Err(context(&path, invalid("invalid registry entry name")));
            }
            let mut bytes = Vec::new();
            fs::File::open(&path)?
                .take(MAX_JSON_BYTES as u64 + 1)
                .read_to_end(&mut bytes)?;
            if bytes.len() > MAX_JSON_BYTES {
                return Err(context(&path, invalid("registry JSON exceeds 1 MiB")));
            }
            total_bytes = total_bytes
                .checked_add(bytes.len())
                .ok_or_else(|| invalid("registry JSON aggregate size overflow"))?;
            if total_bytes > MAX_TOTAL_JSON_BYTES {
                return Err(invalid("registry JSON aggregate exceeds 16 MiB"));
            }
            let mut value: Value = serde_json::from_slice(&bytes)
                .map_err(|e| context(&path, invalid(e.to_string())))?;
            if !value.is_object() {
                return Err(context(
                    &path,
                    invalid("registry entry must be a JSON object"),
                ));
            }
            if registry == "worldgen/biome" {
                value = biome_network_value(value).map_err(|e| context(&path, e))?;
            }
            if registry == "dimension_type" && name == "overworld" {
                validate_overworld(&value).map_err(|e| context(&path, e))?;
            }
            entries.push((name.to_owned(), value));
            if entries.len() > expected_count {
                return Err(context(
                    &directory,
                    invalid("unexpected number of registry entries"),
                ));
            }
        }
        if entries.len() != expected_count {
            return Err(context(
                &directory,
                invalid(format!(
                    "expected {expected_count} entries for protocol 767, found {}",
                    entries.len()
                )),
            ));
        }
        entries.sort_by(|left, right| {
            let prioritized = |name: &str| {
                (registry == "worldgen/biome" && name == "plains")
                    || (registry == "dimension_type" && name == "overworld")
            };
            prioritized(&right.0)
                .cmp(&prioritized(&left.0))
                .then_with(|| left.0.cmp(&right.0))
        });
        let required_first = match registry {
            "worldgen/biome" => Some("plains"),
            "dimension_type" => Some("overworld"),
            _ => None,
        };
        if required_first.is_some_and(|name| entries[0].0 != name) {
            return Err(context(
                &directory,
                invalid("missing required ID-zero entry"),
            ));
        }
        let mut body = Vec::new();
        protocol_string(&format!("minecraft:{registry}"), &mut body)?;
        varint(entries.len(), &mut body)?;
        let entry_names = entries
            .iter()
            .map(|(name, _)| format!("minecraft:{name}"))
            .collect();
        for (name, value) in entries {
            protocol_string(&format!("minecraft:{name}"), &mut body)?;
            push(&mut body, &[1])?; // Entry has complete data; no known-pack elision.
            nbt_root(&value, &mut body)
                .map_err(|e| context(&directory.join(format!("{name}.json")), e))?;
        }
        output.push(Registry {
            name: format!("minecraft:{registry}"),
            count: expected_count,
            body,
            entries: entry_names,
        });
    }
    Ok(output)
}

fn valid_entry_name(name: &str) -> bool {
    !name.is_empty()
        && name != "."
        && name != ".."
        && name.bytes().all(|byte| {
            byte.is_ascii_lowercase() || byte.is_ascii_digit() || b"_-.".contains(&byte)
        })
}

fn biome_network_value(value: Value) -> io::Result<Value> {
    let mut value = value
        .as_object()
        .cloned()
        .ok_or_else(|| invalid("invalid biome object"))?;
    for name in ["has_precipitation", "temperature", "downfall", "effects"] {
        if !value.contains_key(name) {
            return Err(invalid(format!("biome missing network field {name}")));
        }
    }
    if !value["has_precipitation"].is_boolean()
        || !value["temperature"].is_number()
        || !value["downfall"].is_number()
        || !value["effects"].is_object()
    {
        return Err(invalid("invalid biome climate/effects field types"));
    }
    value.retain(|name, _| BIOME_NETWORK_FIELDS.contains(&name.as_str()));
    Ok(Value::Object(value))
}

fn validate_overworld(value: &Value) -> io::Result<()> {
    for (name, expected) in [("min_y", -64), ("height", 384), ("logical_height", 384)] {
        if value[name].as_i64() != Some(expected) {
            return Err(invalid(format!("overworld {name} must equal {expected}")));
        }
    }
    if value["has_skylight"].as_bool() != Some(true) {
        return Err(invalid("overworld must have skylight"));
    }
    Ok(())
}

fn invalid(message: impl Into<String>) -> io::Error {
    io::Error::new(io::ErrorKind::InvalidData, message.into())
}
fn context(path: &Path, error: io::Error) -> io::Error {
    io::Error::new(error.kind(), format!("{}: {error}", path.display()))
}
fn push(out: &mut Vec<u8>, data: &[u8]) -> io::Result<()> {
    if out.len().saturating_add(data.len()) > MAX_PACKET_BYTES {
        return Err(invalid("registry packet exceeds protocol frame limit"));
    }
    out.extend_from_slice(data);
    Ok(())
}
fn varint(value: usize, out: &mut Vec<u8>) -> io::Result<()> {
    let mut value = i32::try_from(value).map_err(|_| invalid("VarInt size overflow"))? as u32;
    loop {
        let low = (value & 0x7f) as u8;
        value >>= 7;
        push(out, &[low | if value == 0 { 0 } else { 0x80 }])?;
        if value == 0 {
            return Ok(());
        }
    }
}
fn protocol_string(value: &str, out: &mut Vec<u8>) -> io::Result<()> {
    if value.len() > 32767 * 3 || value.encode_utf16().count() > 32767 {
        return Err(invalid("protocol string exceeds limit"));
    }
    varint(value.len(), out)?;
    push(out, value.as_bytes())
}
fn nbt_string(value: &str, out: &mut Vec<u8>) -> io::Result<()> {
    let mut encoded = Vec::new();
    for unit in value.encode_utf16() {
        match unit {
            1..=0x7f => encoded.push(unit as u8),
            0..=0x7ff => {
                encoded.push(0xc0 | (unit >> 6) as u8);
                encoded.push(0x80 | (unit & 0x3f) as u8);
            }
            _ => {
                encoded.push(0xe0 | (unit >> 12) as u8);
                encoded.push(0x80 | ((unit >> 6) & 0x3f) as u8);
                encoded.push(0x80 | (unit & 0x3f) as u8);
            }
        }
        if encoded.len() > u16::MAX as usize {
            return Err(invalid("NBT string exceeds modified-UTF8 limit"));
        }
    }
    push(out, &(encoded.len() as u16).to_be_bytes())?;
    push(out, &encoded)
}

fn nbt_root(value: &Value, out: &mut Vec<u8>) -> io::Result<()> {
    if !value.is_object() {
        return Err(invalid("registry NBT root must be a compound"));
    }
    push(out, &[10])?; // Anonymous network root: no name-length field.
    payload(10, value, 0, out)
}
fn tag(value: &Value) -> io::Result<u8> {
    match value {
        Value::Bool(_) => Ok(1),
        Value::Number(number) => {
            if let Some(integer) = number.as_i64() {
                Ok(if i32::try_from(integer).is_ok() { 3 } else { 4 })
            } else if number.is_f64() && number.as_f64().is_some_and(f64::is_finite) {
                Ok(6)
            } else {
                Err(invalid("JSON integer is outside signed NBT Long range"))
            }
        }
        Value::String(_) => Ok(8),
        Value::Array(_) => Ok(9),
        Value::Object(_) => Ok(10),
        Value::Null => Err(invalid("JSON null has no NBT representation")),
    }
}
fn list_tag(values: &[Value]) -> io::Result<u8> {
    if values.len() > MAX_LIST_ENTRIES {
        return Err(invalid("NBT list exceeds entry limit"));
    }
    let Some(first) = values.first() else {
        return Ok(0);
    };
    let first_tag = tag(first)?;
    for value in values {
        tag(value)?;
    }
    if values
        .iter()
        .all(|value| tag(value).ok() == Some(first_tag))
    {
        return Ok(first_tag);
    }
    // Numeric lists may use a common lossless primitive type; all other lists
    // require exactly the same type (booleans are not treated as JSON numbers).
    if values.iter().all(Value::is_number) {
        if values.iter().all(|value| value.as_i64().is_some()) {
            return Ok(4);
        }
        for value in values {
            if let Some(integer) = value.as_i64()
                && (integer as f64) as i128 != i128::from(integer)
            {
                return Err(invalid(
                    "mixed numeric NBT list would lose integer precision",
                ));
            }
        }
        return Ok(6);
    }
    Err(invalid(
        "mixed JSON list cannot be encoded as homogeneous NBT",
    ))
}
fn payload(kind: u8, value: &Value, depth: usize, out: &mut Vec<u8>) -> io::Result<()> {
    if depth > MAX_DEPTH {
        return Err(invalid("registry NBT exceeds nesting limit"));
    }
    match kind {
        1 => push(
            out,
            &[u8::from(
                value.as_bool().ok_or_else(|| invalid("expected boolean"))?,
            )],
        )?,
        3 => {
            let number = value
                .as_i64()
                .and_then(|v| i32::try_from(v).ok())
                .ok_or_else(|| invalid("expected NBT Int"))?;
            push(out, &number.to_be_bytes())?;
        }
        4 => push(
            out,
            &value
                .as_i64()
                .ok_or_else(|| invalid("expected NBT Long"))?
                .to_be_bytes(),
        )?,
        6 => {
            let number = value
                .as_f64()
                .filter(|v| v.is_finite())
                .ok_or_else(|| invalid("expected finite NBT Double"))?;
            push(out, &number.to_be_bytes())?;
        }
        8 => nbt_string(
            value
                .as_str()
                .ok_or_else(|| invalid("expected NBT String"))?,
            out,
        )?,
        9 => {
            let values = value
                .as_array()
                .ok_or_else(|| invalid("expected NBT List"))?;
            let child = list_tag(values)?;
            push(out, &[child])?;
            push(out, &(values.len() as i32).to_be_bytes())?;
            for entry in values {
                payload(child, entry, depth + 1, out)?;
            }
        }
        10 => {
            let fields = value
                .as_object()
                .ok_or_else(|| invalid("expected NBT Compound"))?;
            // Explicit sort keeps output stable even if serde_json's optional
            // preserve_order feature is enabled by another build dependency.
            let mut fields: Vec<_> = fields.iter().collect();
            fields.sort_by_key(|(name, _)| *name);
            for (name, child) in fields {
                let child_kind = tag(child)?;
                push(out, &[child_kind])?;
                nbt_string(name, out)?;
                payload(child_kind, child, depth + 1, out)?;
            }
            push(out, &[0])?;
        }
        _ => return Err(invalid("unsupported NBT tag")),
    }
    Ok(())
}

